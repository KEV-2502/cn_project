"""Visual Results Generator for CIC-IDS2017 Candidate Model Evaluation.

Generates visual charts based on actual evaluation metrics:
1. Confusion Matrix (confusion_matrix.png)
2. Mean Anomaly Score Distribution by Attack Category (anomaly_score_distribution.png)
3. Per-Attack Detection Rate Comparison (per_attack_detection_rates.png)
4. Comprehensive 3-Panel Evaluation Overview (cic_ids2017_evaluation_overview.png)

Figures are saved to experiments/cic_ids2017/reports/figures/.
"""

import json
from pathlib import Path
from typing import Dict, Any, Optional

import matplotlib
matplotlib.use("Agg")  # Headless backend for CLI/server environments
import matplotlib.pyplot as plt
import numpy as np

BASE_DIR = Path(__file__).resolve().parent.parent.parent
REPORTS_DIR = BASE_DIR / "experiments" / "cic_ids2017" / "reports"
FIGURES_DIR = REPORTS_DIR / "figures"
REPORT_JSON_PATH = REPORTS_DIR / "evaluation_report.json"


def load_evaluation_metrics(json_path: Path = REPORT_JSON_PATH) -> Dict[str, Any]:
    """Load actual metrics generated by the evaluation experiment."""
    if not json_path.exists():
        raise FileNotFoundError(
            f"Evaluation report not found at: {json_path}. "
            "Please run experiments/cic_ids2017/run_experiment.py first."
        )
    with open(json_path, "r", encoding="utf-8") as f:
        return json.load(f)


def plot_confusion_matrix(data: Dict[str, Any], output_path: Path) -> Path:
    """Plot and save annotated confusion matrix heatmap."""
    cm = data["confusion_matrix"]
    tn, fp, fn, tp = cm["true_negatives"], cm["false_positives"], cm["false_negatives"], cm["true_positives"]
    matrix = np.array([[tn, fp], [fn, tp]])

    fig, ax = plt.subplots(figsize=(7, 6))
    im = ax.imshow(matrix, cmap="Blues", interpolation="nearest")

    ax.set_xticks([0, 1])
    ax.set_yticks([0, 1])
    ax.set_xticklabels(["Predicted Normal\n(Score < 0.50)", "Predicted Anomaly\n(Score >= 0.50)"], fontsize=11)
    ax.set_yticklabels(["Actual Benign", "Actual Attack"], fontsize=11)

    # Annotate cells
    labels = [
        [f"True Negative (TN)\n{tn:,}\n(98.84% Specificity)", f"False Positive (FP)\n{fp:,}\n(1.16% FPR)"],
        [f"False Negative (FN)\n{fn:,}\n(98.68% Missed)", f"True Positive (TP)\n{tp:,}\n(1.32% Recall)"],
    ]

    thresh = matrix.max() / 2.0
    for i in range(2):
        for j in range(2):
            color = "white" if matrix[i, j] > thresh else "black"
            ax.text(j, i, labels[i][j], ha="center", va="center", color=color, fontsize=11, fontweight="bold")

    ax.set_title("Candidate Isolation Forest — Confusion Matrix (τ = 0.50)\nEvaluated on Sampled CIC-IDS2017 (N = 23,693)", fontsize=12, pad=15)
    plt.colorbar(im, ax=ax, fraction=0.046, pad=0.04)
    plt.tight_layout()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    plt.savefig(output_path, dpi=300)
    plt.close()
    return output_path


def plot_score_distributions(data: Dict[str, Any], output_path: Path) -> Path:
    """Plot mean anomaly score per category with threshold marker."""
    per_class = data["per_class_results"]
    categories = []
    scores = []
    colors = []

    # Sort categories by mean anomaly score
    sorted_items = sorted(per_class.items(), key=lambda x: x[1]["mean_anomaly_score"])

    for name, stats in sorted_items:
        categories.append(name.replace("Web Attack - ", "Web: "))
        scores.append(stats["mean_anomaly_score"])
        if "BENIGN" in name:
            colors.append("#2ecc71")  # Green
        elif stats["mean_anomaly_score"] >= 0.50:
            colors.append("#e74c3c")  # Red (detected as anomaly)
        elif stats["mean_anomaly_score"] >= 0.35:
            colors.append("#e67e22")  # Orange (near boundary)
        else:
            colors.append("#3498db")  # Blue

    fig, ax = plt.subplots(figsize=(10, 7))
    bars = ax.barh(categories, scores, color=colors, edgecolor="black", alpha=0.85)

    # Add threshold reference line
    ax.axvline(0.50, color="red", linestyle="--", linewidth=2, label="Anomaly Decision Threshold (τ = 0.50)")
    ax.set_xlim(0.0, 0.70)
    ax.set_xlabel("Mean Normalized Anomaly Score (Higher = More Abnormal)", fontsize=11)
    ax.set_title("Mean Anomaly Score Across Dataset Categories\n(Candidate Isolation Forest Baseline: Monday Benign)", fontsize=12, pad=15)

    # Annotate score values on bars
    for bar in bars:
        width = bar.get_width()
        ax.text(width + 0.008, bar.get_y() + bar.get_height() / 2, f"{width:.3f}", va="center", fontsize=9, fontweight="bold")

    ax.legend(loc="lower right", fontsize=10)
    ax.grid(axis="x", linestyle=":", alpha=0.6)
    plt.tight_layout()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    plt.savefig(output_path, dpi=300)
    plt.close()
    return output_path


def plot_detection_rates(data: Dict[str, Any], output_path: Path) -> Path:
    """Plot per-attack category recall / detection rate bar chart."""
    per_class = data["per_class_results"]
    attack_items = [
        (k.replace("Web Attack - ", "Web: "), v["rate"] * 100, v["sample_count"], v["flagged_count"])
        for k, v in per_class.items()
        if v["category"] == "ATTACK"
    ]
    attack_items.sort(key=lambda x: x[1])

    categories = [x[0] for x in attack_items]
    rates = [x[1] for x in attack_items]
    sample_counts = [x[2] for x in attack_items]
    flagged_counts = [x[3] for x in attack_items]

    fig, ax = plt.subplots(figsize=(10, 7))
    colors = ["#e74c3c" if r > 50 else "#e67e22" if r > 0 else "#95a5a6" for r in rates]
    bars = ax.barh(categories, rates, color=colors, edgecolor="black", alpha=0.85)

    ax.set_xlim(0, 115)
    ax.set_xlabel("Detection Rate / Recall (%) at Decision Threshold τ = 0.50", fontsize=11)
    ax.set_title("Per-Attack Category Detection Rate (Unsupervised Isolation Forest)\nEvaluated on Sampled CIC-IDS2017 Attacks (N = 13,693)", fontsize=12, pad=15)

    for i, bar in enumerate(bars):
        width = bar.get_width()
        cnt_text = f"{rates[i]:.1f}% ({flagged_counts[i]}/{sample_counts[i]})"
        ax.text(width + 1.5, bar.get_y() + bar.get_height() / 2, cnt_text, va="center", fontsize=9, fontweight="bold")

    ax.grid(axis="x", linestyle=":", alpha=0.6)
    plt.tight_layout()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    plt.savefig(output_path, dpi=300)
    plt.close()
    return output_path


def plot_composite_overview(data: Dict[str, Any], output_path: Path) -> Path:
    """Generate a combined 3-panel evaluation overview figure."""
    fig = plt.figure(figsize=(18, 6))

    # Panel 1: Confusion Matrix
    ax1 = fig.add_subplot(1, 3, 1)
    cm = data["confusion_matrix"]
    tn, fp, fn, tp = cm["true_negatives"], cm["false_positives"], cm["false_negatives"], cm["true_positives"]
    matrix = np.array([[tn, fp], [fn, tp]])
    im = ax1.imshow(matrix, cmap="Blues", interpolation="nearest")
    ax1.set_xticks([0, 1])
    ax1.set_yticks([0, 1])
    ax1.set_xticklabels(["Pred Normal", "Pred Anomaly"], fontsize=10)
    ax1.set_yticklabels(["Actual Benign", "Actual Attack"], fontsize=10)
    labels = [
        [f"TN: {tn:,}\n(FPR: 1.16%)", f"FP: {fp:,}\n(Prec: 60.9%)"],
        [f"FN: {fn:,}\n(Missed)", f"TP: {tp:,}\n(Recall: 1.3%)"],
    ]
    for i in range(2):
        for j in range(2):
            color = "white" if matrix[i, j] > (matrix.max() / 2) else "black"
            ax1.text(j, i, labels[i][j], ha="center", va="center", color=color, fontsize=10, fontweight="bold")
    ax1.set_title("A. Confusion Matrix (τ = 0.50)", fontsize=11, fontweight="bold")

    # Panel 2: Mean Anomaly Scores
    ax2 = fig.add_subplot(1, 3, 2)
    per_class = data["per_class_results"]
    sorted_items = sorted(per_class.items(), key=lambda x: x[1]["mean_anomaly_score"])
    cats = [k.replace("Web Attack - ", "Web: ") for k, v in sorted_items]
    scores = [v["mean_anomaly_score"] for k, v in sorted_items]
    bar_colors = ["#2ecc71" if "BENIGN" in c else "#e74c3c" if s >= 0.5 else "#3498db" for c, s in zip(cats, scores)]
    ax2.barh(cats, scores, color=bar_colors, alpha=0.85)
    ax2.axvline(0.50, color="red", linestyle="--", linewidth=1.5, label="Threshold (0.50)")
    ax2.set_xlim(0, 0.70)
    ax2.set_xlabel("Mean Score", fontsize=10)
    ax2.set_title("B. Mean Anomaly Score by Class", fontsize=11, fontweight="bold")
    ax2.legend(loc="lower right", fontsize=8)

    # Panel 3: Detection Rates
    ax3 = fig.add_subplot(1, 3, 3)
    attack_items = [
        (k.replace("Web Attack - ", "Web: "), v["rate"] * 100)
        for k, v in per_class.items()
        if v["category"] == "ATTACK"
    ]
    attack_items.sort(key=lambda x: x[1])
    a_cats = [x[0] for x in attack_items]
    a_rates = [x[1] for x in attack_items]
    ax3.barh(a_cats, a_rates, color="#e67e22", alpha=0.85)
    ax3.set_xlim(0, 110)
    ax3.set_xlabel("Detection Rate (%)", fontsize=10)
    ax3.set_title("C. Per-Attack Detection Recall (%)", fontsize=11, fontweight="bold")
    for i, v in enumerate(a_rates):
        ax3.text(v + 1.5, i, f"{v:.1f}%", va="center", fontsize=8, fontweight="bold")

    plt.suptitle("CIC-IDS2017 Candidate Isolation Forest Evaluation Overview (Isolated Offline Experiment)", fontsize=13, y=0.98)
    plt.tight_layout()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    plt.savefig(output_path, dpi=300)
    plt.close()
    return output_path


def generate_all_plots(reports_dir: Path = REPORTS_DIR) -> Dict[str, Path]:
    """Generate all evaluation visual charts and return map of generated paths."""
    data = load_evaluation_metrics(reports_dir / "evaluation_report.json")
    figures_dir = reports_dir / "figures"
    figures_dir.mkdir(parents=True, exist_ok=True)

    cm_path = plot_confusion_matrix(data, figures_dir / "confusion_matrix.png")
    dist_path = plot_score_distributions(data, figures_dir / "anomaly_score_distribution.png")
    det_path = plot_detection_rates(data, figures_dir / "per_attack_detection_rates.png")
    comp_path = plot_composite_overview(data, figures_dir / "cic_ids2017_evaluation_overview.png")

    return {
        "confusion_matrix": cm_path,
        "score_distribution": dist_path,
        "detection_rates": det_path,
        "composite_overview": comp_path,
    }


if __name__ == "__main__":
    generated = generate_all_plots()
    print("Visual figures successfully generated:")
    for name, path in generated.items():
        print(f"  {name:<20}: {path}")
